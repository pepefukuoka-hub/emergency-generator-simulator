def deck(g, xa, xb, ya, yb, s, notch=None):
    """点検デッキ。s=+1 が操作側（+y）。ya＝機械側の縁、yb＝通路側の縁（どちらも正の値で渡す）"""
    with g.at(S(1, s, 1)):
        with g.use('static', 'big'):
            if notch:
                na, nb, ny = notch
                poly = [(xa, ya), (na, ya), (na, ny), (nb, ny), (nb, ya), (xb, ya), (xb, yb), (xa, yb)]
            else: poly = [(xa, ya), (xb, ya), (xb, yb), (xa, yb)]
            g.prism('checker', poly, 'z', 0.752, 0.76, bev=0.002)
            g.box(A, xa, xb, yb - 0.008, yb, 0.57, 0.752, bev=0.002)                       # 通路側の前板
            for x in (xa, xb - 0.008): g.box(A, x, x + 0.008, ya, yb, 0.66, 0.752, bev=0.002)
            g.box(A, xa, xb, ya, ya + 0.05, 0.70, 0.752, bev=0.002)
            for x in (xa + 0.12, (xa + xb) / 2, xb - 0.12): g.prism(A, [(0.69, 0.70), (yb - 0.05, 0.70), (yb - 0.05, 0.66), (0.69, 0.34)], 'x', x - 0.006, x + 0.006, bev=0)   # 架台から張り出す腕
